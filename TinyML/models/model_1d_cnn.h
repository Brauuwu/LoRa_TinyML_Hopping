/**
 * Chuẩn hóa bộ đệm trượt 10 bước (mỗi bước 8 đặc trưng) thành vector 80 chiều
 */
inline void normalizeSlidingWindow(const float raw_history[10][8], float out_normalized[80]) {
  int idx = 0;
  for (int step = 0; step < 10; step++) {
    for (int feat = 0; feat < 8; feat++) {
#if defined(SCALER_MEAN)
      out_normalized[idx] = (raw_history[step][feat] - SCALER_MEAN[feat]) / SCALER_SCALE[feat];
#else
      out_normalized[idx] = (raw_history[step][feat] - SCALER_MEAN_80[idx]) / SCALER_SCALE_80[idx];
#endif
      idx++;
    }
  }
}

/**
 * Tìm chỉ số kênh có xác suất lớn nhất (ArgMax)
 */
inline int argmaxChannel(const float probs[3]) {
  int best = 0;
  float max_val = probs[0];
  for (int i = 1; i < 3; i++) {
    if (probs[i] > max_val) {
      max_val = probs[i];
      best = i;
    }
  }
  return best;
}
