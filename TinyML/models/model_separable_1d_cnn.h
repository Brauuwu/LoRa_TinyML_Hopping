/**
 * Chuẩn hóa bộ đệm trượt 10 bước (mỗi bước 9 đặc trưng) thành vector 90 chiều
 */
inline void normalizeSlidingWindow(const float raw_history[10][9], float out_normalized[90]) {
  int idx = 0;
  for (int step = 0; step < 10; step++) {
    for (int feat = 0; feat < 9; feat++) {
#if defined(SCALER_MEAN)
      out_normalized[idx] = (raw_history[step][feat] - SCALER_MEAN[feat]) / SCALER_SCALE[feat];
#else
      out_normalized[idx] = (raw_history[step][feat] - SCALER_MEAN_90[idx]) / SCALER_SCALE_90[idx];
#endif
      idx++;
    }
  }
}

/**
 * Tìm chỉ số kênh có xác suất lớn nhất (ArgMax)
 */
inline int argmaxChannel(const float probs[3]) {
  int best = 0;
  float max_val = probs[0];
  for (int i = 1; i < 3; i++) {
    if (probs[i] > max_val) {
      max_val = probs[i];
      best = i;
    }
  }
  return best;
}
